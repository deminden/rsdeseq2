#!/usr/bin/env Rscript
args <- commandArgs(TRUE)
if(length(args)!=3L)stop('usage: STANDALONE_DRIVER R_LIBRARY FRESH_OUTPUT_DIR')
driver <- normalizePath(args[[1L]])
library(rsdeseq2,lib.loc=normalizePath(args[[2L]]))
script <- sub('^--file=','',grep('^--file=',commandArgs(FALSE),value=TRUE)[[1L]])
root <- normalizePath(file.path(dirname(gsub('~+~',' ',script,fixed=TRUE)),'..'))
source(file.path(root,'r-pkg/rsdeseq2/tests/testthat/helper-formula.R'))
out <- args[[3L]];if(dir.exists(out))stop('Use a fresh output directory');dir.create(out,recursive=TRUE)
r <- jsonlite::fromJSON(file.path(root,'crates/rsdeseq2/tests/data/mixture_grid_r462.json'),simplifyVector=FALSE)
fields <- c('family','estimates','standard_errors','scales','point_mass','mode','range','nullweight')
cases <- lapply(r$cases,function(c)c[c('name',fields)])
path <- file.path(out,'input.json');jsonlite::write_json(list(grid_cases=cases),path,auto_unbox=TRUE,null='null',digits=NA)
output <- system2(driver,shQuote(normalizePath(path)),stdout=TRUE,stderr=TRUE)
if(!is.null(attr(output,'status')))stop(paste(output,collapse='\n'))
standalone <- jsonlite::fromJSON(paste(output,collapse='\n'),simplifyVector=FALSE)
decode <- function(v)vapply(v,function(h){h<-sub('^bits:','',h);readBin(as.raw(strtoi(substring(h,seq(1L,15L,2L),seq(2L,16L,2L)),16L)),'double',n=1L,size=8L,endian='big')},numeric(1L))
blocked <- function(expression){
 functions<-c('sqrt','exp','log','log2','ceiling','min','max','sum','^')
 on.exit(for(name in functions)suppressMessages(untrace(name,where=baseenv())),add=TRUE)
 for(name in functions)suppressWarnings(suppressMessages(trace(name,where=baseenv(),print=FALSE,tracer=quote(stop('grid bridge executed an R calculation',call.=FALSE)))))
 force(expression)
}
guard <- tryCatch(blocked(sqrt(2)),error=identity);stopifnot(inherits(guard,'error'),grepl('executed an R calculation',conditionMessage(guard)))
wrapped <- lapply(cases,function(c){
 request <- c(list(operation='mixture_grid'),c[fields])
 for(f in c('estimates','standard_errors','scales','mode','range','nullweight'))if(!is.null(request[[f]]))request[[f]]<-decode(request[[f]])
 result <- blocked(rsdeseq2:::.rsdeseq2_formula_request(request))
 result <- lapply(result,function(v)if(is.numeric(v))lapply(unname(v),hex)else if(is.character(v))as.list(unname(v))else v)
 result$component_class <- result$component_class[[1L]]
 c(list(name=c$name),result)
})
canonical <- function(x){if(!is.list(x))return(x);if(!is.null(names(x)))x<-x[sort(names(x))];lapply(x,canonical)}
wrapped <- .formula_canonical(list(cases=wrapped))
jsonlite::write_json(wrapped,file.path(out,'wrapped.json'),pretty=TRUE,auto_unbox=TRUE,null='null')
writeLines(output,file.path(out,'standalone.json'))
stopifnot(identical(canonical(wrapped),canonical(standalone)))
cat(length(cases),'grids across all six families: every bit and warning matches; R calculations blocked\n')
