#!/usr/bin/env python3
"""List normal dependencies whose licence expression has no MIT option.

Walks `cargo tree` for every workspace crate, once with default features and
once with all features, and writes a Markdown report. Dev- and
build-dependencies are excluded because they do not ship in the library.

Usage: scripts/provenance/dependency_licences.py [--write PATH | --check PATH]
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CRATES = ["rcompat-numeric", "rcompat-formula", "rcompat-shrinkage", "rsdeseq2"]


def has_mit_option(expr: str) -> bool:
    """True when the SPDX expression can be satisfied by MIT alone."""
    expr = expr.strip().replace("/", " OR ")
    if not expr:
        return False
    for alternative in re.split(r"\s+OR\s+", expr):
        alternative = alternative.strip().strip("()").strip()
        if re.split(r"\s+AND\s+", alternative) == ["MIT"]:
            return True
    return False


def tree(package: str, all_features: bool) -> list[tuple[str, str, str]]:
    cmd = [
        "cargo", "tree", "--locked", "-p", package, "-e", "normal",
        "--prefix", "none", "--no-dedupe", "-f", "{p}\t{l}",
    ]
    if all_features:
        cmd.append("--all-features")
    out = subprocess.run(cmd, cwd=ROOT, check=True, capture_output=True, text=True).stdout
    rows = set()
    for line in out.splitlines():
        if "\t" not in line:
            continue
        pkg, lic = line.split("\t", 1)
        fields = pkg.split()
        name, version = fields[0], fields[1].lstrip("v")
        if name in CRATES:
            continue
        rows.add((name, version, lic.strip()))
    return sorted(rows)


def report() -> str:
    lines = [
        "# Dependencies without an MIT option",
        "",
        "Generated by `scripts/provenance/dependency_licences.py` from `cargo tree`",
        "(normal edges only; dev- and build-dependencies are not shipped).",
        "A dependency is listed when no alternative of its licence expression is MIT alone.",
        "",
    ]
    for crate in CRATES:
        for all_features, label in ((False, "default features"), (True, "all features")):
            bad = [r for r in tree(crate, all_features) if not has_mit_option(r[2])]
            lines.append(f"## {crate}, {label}")
            lines.append("")
            if not bad:
                lines.append("None.")
            else:
                lines.append("| Crate | Version | Licence |")
                lines.append("|---|---|---|")
                for name, version, lic in bad:
                    lines.append(f"| {name} | {version} | {lic or '(none declared)'} |")
            lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", type=Path, help="write the report to this path")
    group.add_argument("--check", type=Path, help="fail if this file differs from the report")
    args = parser.parse_args()
    text = report()
    if args.write:
        (ROOT / args.write).write_text(text)
    elif args.check:
        if (ROOT / args.check).read_text() != text:
            print(f"{args.check} is out of date; rerun with --write", file=sys.stderr)
            return 1
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
