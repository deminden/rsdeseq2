#!/usr/bin/env python3
"""Generate crates/rcompat-collate/src/table.rs from the collation probe output.

The input is docs/provenance/observations/collation_r462_macos/collation_table.tsv
and contractions.tsv, written by scripts/provenance/probe_collation.R from
black-box runs of R. Each collation element "p.s.t" is packed as
p << 16 | s << 8 | t.

Usage: build_collation_table.py [--check]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OBSERVATIONS = ROOT / "docs/provenance/observations/collation_r462_macos"
OUTPUT = ROOT / "crates/rcompat-collate/src/table.rs"


def read_rows(path: Path) -> list[list[str]]:
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        rows.append(line.split("\t"))
    return rows


def pack(element: str) -> int:
    primary, secondary, tertiary = (int(part) for part in element.split("."))
    if not (primary < 1 << 16 and 0 < secondary < 1 << 8 and 0 < tertiary < 1 << 8):
        raise ValueError(f"weight out of range: {element}")
    return primary << 16 | secondary << 8 | tertiary


def chunked(values: list[str], per_line: int) -> str:
    lines = []
    for start in range(0, len(values), per_line):
        lines.append("    " + ", ".join(values[start : start + per_line]) + ",")
    return "\n".join(lines)


def render() -> str:
    code_points: list[int] = []
    offsets = [0]
    elements: list[int] = []
    max_primary = 0
    for row in read_rows(OBSERVATIONS / "collation_table.tsv"):
        code_points.append(int(row[0], 16))
        packed = [pack(e) for e in row[1].split()] if len(row) > 1 and row[1] else []
        max_primary = max([max_primary] + [value >> 16 for value in packed])
        elements.extend(packed)
        offsets.append(len(elements))
    if code_points != sorted(set(code_points)):
        raise ValueError("code points must be unique and sorted")
    contractions = []
    for first, second, equal in read_rows(OBSERVATIONS / "contractions.tsv"):
        contractions.append((int(first, 16), int(second, 16), int(equal, 16)))
    contractions.sort()
    for _, _, equal in contractions:
        if equal not in code_points:
            raise ValueError(f"contraction target {equal:04X} is not in the table")
    return f"""//! Collation weights derived from black-box runs of R 4.6.2 (ICU root).
//!
//! Generated by `scripts/provenance/build_collation_table.py` from
//! `docs/provenance/observations/collation_r462_macos`; do not edit. The
//! method is described in `docs/provenance/specs/collation.md`.

/// Number of primary weights in the table; unlisted code points sort after them.
pub(crate) const PRIMARY_COUNT: u32 = {max_primary};

/// Code points with observed collation elements, in increasing order.
#[rustfmt::skip]
pub(crate) static CODE_POINTS: [u32; {len(code_points)}] = [
{chunked([f"0x{cp:04X}" for cp in code_points], 12)}
];

/// `ELEMENTS[OFFSETS[i]..OFFSETS[i + 1]]` are the elements of `CODE_POINTS[i]`.
#[rustfmt::skip]
pub(crate) static OFFSETS: [u16; {len(offsets)}] = [
{chunked([str(v) for v in offsets], 16)}
];

/// Collation elements packed as `primary << 16 | secondary << 8 | tertiary`.
#[rustfmt::skip]
pub(crate) static ELEMENTS: [u32; {len(elements)}] = [
{chunked([f"0x{v:08X}" for v in elements], 8)}
];

/// Two-character contractions: (first, second, code point with the same elements).
pub(crate) static CONTRACTIONS: [(u32, u32, u32); {len(contractions)}] = [
{chr(10).join(f"    (0x{a:04X}, 0x{b:04X}, 0x{c:04X})," for a, b, c in contractions)}
];
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the table is out of date")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date", file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
