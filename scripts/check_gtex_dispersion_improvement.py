#!/usr/bin/env python3
"""Measure maximum-error reductions against frozen GTEx DESeq2 references.

The baseline metrics must come from the pre-change native CLI outputs. The
reference files and contrast designs are never regenerated by this checker.
"""
from __future__ import annotations
import argparse
import csv
import hashlib
import math
import os
import subprocess
import statistics
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULT_COLUMNS = ('baseMean', 'dispersion', 'log2FoldChange', 'lfcSE', 'stat', 'pvalue', 'padj')
STAGE_COLUMNS = ('dispGeneEst', 'dispFit', 'dispMAP', 'dispersion')
TARGET_CONTRASTS = ('sex_female_vs_male', 'male_age4_vs_age3',
                    'unblocked_random_rep01', 'unblocked_random_rep02', 'unblocked_random_rep03')

def read_rows(path):
    with path.open(newline='') as handle:
        return list(csv.DictReader(handle, delimiter='\t'))

def write_rows(path, rows):
    with path.open('w', newline='') as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]), delimiter='\t', lineterminator='\n')
        writer.writeheader()
        writer.writerows(rows)

def numeric(value):
    return math.nan if value in ('NA', 'NaN', '') else float(value)

def compare(actual, reference, columns):
    got = {row['gene']: row for row in read_rows(actual)}
    expected = {row['gene']: row for row in read_rows(reference)}
    if got.keys() != expected.keys():
        raise ValueError(f'gene coverage mismatch: {actual}')
    rows = []
    for column in columns:
        errors = []
        mismatches = 0
        worst_gene = ''
        maximum = -1.0
        for gene, row in expected.items():
            a, b = numeric(got[gene][column]), numeric(row[column])
            if math.isfinite(a) != math.isfinite(b):
                mismatches += 1
            elif math.isfinite(a):
                error = abs(a-b)
                errors.append(error)
                if error > maximum:
                    maximum, worst_gene = error, gene
        errors.sort()
        n = len(errors)
        rows.append(dict(column=column, n_genes=len(expected), n_finite=n,
            finite_na_mismatches=mismatches,
            median_abs=errors[n//2] if n else math.nan,
            p99_abs=errors[min(n-1, int(.99*n))] if n else math.nan,
            max_abs=maximum, worst_gene=worst_gene))
    return rows

def global_maxima(rows, required_reduction):
    output=[]
    for category, columns in (('dispersion_stage',STAGE_COLUMNS),
                              ('result',('log2FoldChange','lfcSE','stat','pvalue','padj'))):
        for column in columns:
            selected=[r for r in rows if r['category']==category and r['column']==column]
            before=max(float(r['before_max_abs']) for r in selected)
            after=max(float(r['after_max_abs']) for r in selected)
            factor=before/after if after > 0 else math.inf
            output.append(dict(category=category,column=column,before_global_max_abs=before,
                after_global_max_abs=after,reduction_factor=factor,passed=factor >= required_reduction))
    return output

def stage_routes(contrast, after_dir):
    expected = {r['gene']:r for r in read_rows(contrast/'reference_fit_diagnostics.tsv')}
    before = {r['gene']:r for r in read_rows(contrast/'rust_fit_diagnostics.tsv')}
    after = {r['gene']:r for r in read_rows(after_dir/'diagnostics.tsv')}
    means = {r['gene']:numeric(r['baseMean']) for r in read_rows(contrast/'reference_results.tsv')}
    finite = {g for g,r in expected.items() if math.isfinite(numeric(r['dispGeneEst']))}
    low = min(finite,key=lambda g:means[g])
    high = max(finite,key=lambda g:means[g])
    output = dict(contrast=contrast.name)
    samples = len(next(csv.reader((contrast/'counts.tsv').open(),delimiter='\t')))-1
    coefficients = len(next(csv.reader((contrast/'design_matrix.tsv').open(),delimiter='\t')))-1
    df = samples-coefficients
    # All eleven contrasts have df > 3; the ordinary robust prior is used.
    x = df/2
    inv = 1/x
    sampling_variance = inv+inv*inv/2+inv**3/6-inv**5/30+inv**7/42-inv**9/30
    ref_masks = None
    for label, table in [('reference',expected),('before',before),('after',after)]:
        eligible = {g for g in finite if numeric(table[g]['dispGeneEst']) > 1e-6}
        robust = {g for g in eligible if 1e-4 < numeric(table[g]['dispGeneEst'])/numeric(table[g]['dispFit']) < 15}
        fallback = {g for g in finite if numeric(table[g]['dispIter']) >= 100}
        outliers = {g for g in finite if table[g]['dispOutlier'].lower() == 'true'}
        if ref_masks is None:ref_masks = (eligible,robust,fallback,outliers)
        for field, mask, refmask in zip(('trend_eligible','trend_robust_screen','map_grid_fallback','dispersion_outliers'),
                                       (eligible,robust,fallback,outliers),ref_masks):
            output[label+'_'+field+'_count'] = len(mask)
            output[label+'_'+field+'_mismatches'] = len(mask ^ refmask)
        f_low, f_high = numeric(table[low]['dispFit']),numeric(table[high]['dispFit'])
        extra = (f_low-f_high)/(1/means[low]-1/means[high])
        output[label+'_extra_pois'] = extra
        output[label+'_asympt_disp'] = f_high-extra/means[high]
        residuals = [math.log(numeric(table[g]['dispGeneEst']))-math.log(numeric(table[g]['dispFit']))
                     for g in finite if numeric(table[g]['dispGeneEst']) >= 1e-6]
        center = statistics.median(residuals)
        var = (1.4826*statistics.median(abs(v-center) for v in residuals))**2
        output[label+'_derived_var_log_disp'] = var
        output[label+'_derived_prior_var'] = max(var-sampling_variance,0.25)
    return output

def sha256(path):
    digest = hashlib.sha256()
    with path.open('rb') as handle:
        for block in iter(lambda: handle.read(1024*1024), b''):
            digest.update(block)
    return digest.hexdigest()

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fixture-root', type=Path, default=ROOT/'results/benchmarks/gtex_mode_contrasts')
    parser.add_argument('--baseline-root', type=Path, default=ROOT/'results/benchmarks/gtex_dispersion_improvement/before')
    parser.add_argument('--output-dir', type=Path, default=ROOT/'results/benchmarks/gtex_dispersion_improvement/after')
    parser.add_argument('--binary', type=Path, default=ROOT/'target/release/rsdeseq2')
    parser.add_argument('--reference-hashes', type=Path, default=ROOT/'docs/data/gtex_dispersion_reference_sha256.tsv')
    parser.add_argument('--workers', type=int, default=2)
    parser.add_argument('--required-reduction', type=float, default=100.0)
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    contrasts = [args.fixture_root/name for name in ('condition_blocked','sex_female_vs_male','male_age4_vs_age3')]
    contrasts += sorted((args.fixture_root/'random_splits').glob('*_random_rep*'))
    if len(contrasts) != 11 or {d.name for d in contrasts}.issuperset(TARGET_CONTRASTS) is False:
        raise ValueError('expected all 11 original, biological, and randomized contrasts')
    baseline = {}
    if (args.baseline_root/'summary.tsv').exists():
        for row in read_rows(args.baseline_root/'summary.tsv'):
            if row['route'] == 'native': baseline[(row['contrast'],'result',row['column'])] = float(row['max_abs'])
        for row in read_rows(args.baseline_root/'dispersion_stage_summary.tsv'):
            baseline[(row['contrast'],'dispersion_stage',row['column'])] = float(row['max_abs'])
    else:
        for row in read_rows(ROOT/'docs/data/gtex_dispersion_improvement.tsv'):
            baseline[(row['contrast'],row['category'],row['column'])] = float(row['before_max_abs'])
    frozen_hashes = []
    for d in contrasts:
        for name in ('counts.tsv','design_matrix.tsv','reference_results.tsv','reference_fit_diagnostics.tsv'):
            path = d/name
            frozen_hashes.append(dict(contrast=d.name, file=name, sha256=sha256(path)))

    if args.reference_hashes.exists():
        published = {(r['contrast'],r['file']):r['sha256'] for r in read_rows(args.reference_hashes)}
        for row in frozen_hashes:
            if published[(row['contrast'],row['file'])] != row['sha256']:
                raise ValueError('input/reference hash differs from the frozen comparison: '
                                 + row['contrast']+'/'+row['file'])

    def run(d):
        out = args.output_dir/d.name
        out.mkdir(parents=True, exist_ok=True)
        env = os.environ.copy()
        env['RAYON_NUM_THREADS'] = '4'
        subprocess.run([str(args.binary.resolve()),'wald','--counts',str(d/'counts.tsv'),
            '--design',str(d/'design_matrix.tsv'),'--output',str(out/'results.tsv'),
            '--fit-diagnostics-output',str(out/'diagnostics.tsv'),
            '--disable-cooks-cutoff','--disable-independent-filtering'],check=True,env=env)
        rows=[]
        for category, got, ref, columns in (
            ('result',out/'results.tsv',d/'reference_results.tsv',RESULT_COLUMNS),
            ('dispersion_stage',out/'diagnostics.tsv',d/'reference_fit_diagnostics.tsv',STAGE_COLUMNS)):
            for metrics in compare(got,ref,columns):
                key=(d.name,category,metrics['column'])
                old=baseline[key]
                new=metrics['max_abs']
                factor=old/new if new > 0 else math.inf
                target=d.name in TARGET_CONTRASTS and metrics['column'] != 'baseMean'
                coverage_ok=metrics['finite_na_mismatches'] == 0
                passed=coverage_ok and (factor >= args.required_reduction if target else new <= old*1.05+1e-10)
                rows.append(dict(contrast=d.name,category=category,column=metrics['column'],
                    before_max_abs=old,after_max_abs=new,reduction_factor=factor,
                    required_reduction=args.required_reduction if target else 0,
                    passed=passed,n_genes=metrics['n_genes'],n_finite=metrics['n_finite'],
                    finite_na_mismatches=metrics['finite_na_mismatches'],
                    after_median_abs=metrics['median_abs'],after_p99_abs=metrics['p99_abs'],
                    worst_gene=metrics['worst_gene']))
        print(f'completed {d.name}',flush=True)
        return rows
    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        rows=[row for result in pool.map(run,contrasts) for row in result]
    write_rows(args.output_dir/'comparison.tsv',rows)
    overall=global_maxima(rows,args.required_reduction)
    write_rows(args.output_dir/'global_maxima.tsv',overall)
    write_rows(args.output_dir/'stage_routes.tsv',[stage_routes(d,args.output_dir/d.name) for d in contrasts])
    # Verify the checker did not change any count, design, or reference file.
    for row in frozen_hashes:
        d=next(d for d in contrasts if d.name == row['contrast'])
        if sha256(d/row['file']) != row['sha256']:
            raise ValueError('a frozen input or reference changed during the comparison')
    write_rows(args.output_dir/'reference_sha256.tsv',frozen_hashes)
    (args.output_dir/'binary_sha256.txt').write_text(sha256(args.binary)+'\n')
    source_paths = sorted((ROOT/'crates/rsdeseq2/src').rglob('*.rs')) + [ROOT/'Cargo.toml',ROOT/'Cargo.lock']
    write_rows(args.output_dir/'source_sha256.tsv',[dict(path=str(p.relative_to(ROOT)),sha256=sha256(p)) for p in source_paths])
    failures=[r for r in rows if not r['passed']]
    for row in failures:
        print('FAILED',row['contrast'],row['category'],row['column'],row['reduction_factor'])
    target_rows=[r for r in rows if r['required_reduction']]
    print(f'{len(rows)-len(failures)}/{len(rows)} gates passed; minimum target reduction: '
          f'{min(r["reduction_factor"] for r in target_rows):.3g}x',flush=True)
    global_failures=[r for r in overall if not r['passed']]
    print(f'{len(overall)-len(global_failures)}/{len(overall)} global-maximum gates passed; '
          f'minimum global reduction: {min(r["reduction_factor"] for r in overall):.3g}x',flush=True)
    return 1 if failures or global_failures else 0

if __name__ == '__main__':
    raise SystemExit(main())
