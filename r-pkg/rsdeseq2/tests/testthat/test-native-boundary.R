test_that("registered native calls reject malformed buffers in a child process", {
  dll <- normalizePath(getLoadedDLLs()[["rsdeseq2"]][["path"]])
  script <- tempfile(fileext = ".R")
  on.exit(unlink(script), add = TRUE)
  writeLines(c(
    sprintf("dyn.load(%s)", deparse(dll)),
    'ct <- matrix(as.double(1:12), 3, 4)',
    'dm <- cbind(1, c(0,0,1,1))',
    'call <- function(name, ...) .Call(name, ..., PACKAGE="rsdeseq2")',
    'bad <- list(',
    'function() call("rsdeseq2_wald_statistics",c(1,2),1,0,0L,FALSE,NULL),',
    'function() call("rsdeseq2_wald_statistics",1,1L,0,0L,FALSE,NULL),',
    'function() call("rsdeseq2_wald_statistics",c(1,2),c(1,1),0,0L,TRUE,c(1,2,3)),',
    'function() call("rsdeseq2_wald_statistics",1,1,0,6L,FALSE,NULL),',
    'function() call("rsdeseq2_wald_statistics",1,1,0,0L,NA,NULL),',
    'function() call("rsdeseq2_lrt_pvalues",1L,2),',
    'function() call("rsdeseq2_lrt_pvalues",c(1,2),c(1,2,3)),',
    'function() call("rsdeseq2_default_cooks_cutoff",Inf,2L),',
    'function() call("rsdeseq2_bh_adjust", 1L),',
    'function() call("rsdeseq2_independent_filtering", rep(1,2), rep(.1,3), NULL, .1, TRUE),',
    'function() call("rsdeseq2_independent_filtering", rep(1,3), rep(.1,3), c(0,1), .1, NA),',
    'function() call("rsdeseq2_normalized_counts", ct, 1, NULL),',
    'function() call("rsdeseq2_base_mean", ct, NULL, matrix(1, 2, 4)),',
    'function() call("rsdeseq2_base_metadata", ct, NULL, NULL, matrix(1, 3, 3)),',
    'function() call("rsdeseq2_estimate_size_factors", ct, c(1,1), NULL, 0L),',
    'function() call("rsdeseq2_estimate_size_factors", ct, NULL, c(NA_integer_), 0L),',
    'function() call("rsdeseq2_estimate_size_factors", ct, NULL, 1L, 2^32),',
    'function() call("rsdeseq2_apply_cooks_cutoff", rep(.5,3), 1, 1, NULL, NULL, FALSE),',
    'function() call("rsdeseq2_apply_cooks_cutoff", rep(.5,3), rep(1,3), 1, ct, matrix(1,3,3), TRUE),',
    'function() call("rsdeseq2_fit", ct, dm, NULL, NULL, NULL, NULL, 2L, 0L, 0L, 1, NA_integer_, 0L),',
    'function() call("rsdeseq2_transform", ct, dm, NULL, NULL, NULL, 2L, 1L, FALSE, 0L, 1L, 1, 1, -1L, NULL, NULL, NULL),',
    'function() call("rsdeseq2_lfc_shrink_normal_contrast", ct, dm, NULL, NULL, NULL, rep(.1,3), rep(1,3), rep(.1,3), matrix(0,3,2), c(0,1), c(0L,1L), c(0L,1L), c(0,1), 1L, 1L, 0),',
    'function() call("rsdeseq2_lfc_shrink_normal", ct, dm, 1, NULL, NULL, rep(.1,3), rep(1,3), rep(.1,3), 2L, 0L, 0)',
    ')',
    'for (i in seq_along(bad)) {',
    '  ans <- tryCatch({bad[[i]](); NULL}, error=identity)',
    '  if (!inherits(ans,"error")) stop(sprintf("malformed case %d succeeded", i))',
    '  stopifnot(grepl("required type and length|dimensions|indices|integer range|TRUE or FALSE|scalar or one per gene", conditionMessage(ans)))',
    '}',
    'empty <- call("rsdeseq2_wald_statistics",numeric(),numeric(),0,0L,TRUE,numeric())',
    'stopifnot(length(empty$stat)==0L,length(empty$pvalue)==0L)',
    'unsupported <- tryCatch(call("rsdeseq2_wald_statistics",numeric(),numeric(),1,1L,TRUE,numeric()),error=identity)',
    'stopifnot(inherits(unsupported,"error"),grepl("greaterAbsUPSHOT",conditionMessage(unsupported)))',
    'wald <- call("rsdeseq2_wald_statistics",c(1,-1,0,NA_real_),rep(1,4),0,0L,FALSE,NULL)',
    'stopifnot(identical(wald$stat,c(1,-1,0,NA_real_)),isTRUE(all.equal(wald$pvalue,2*pnorm(c(1,1,0,NA_real_),lower.tail=FALSE),tolerance=1e-15)))',
    't <- call("rsdeseq2_wald_statistics",c(1/sqrt(.5),-1.5),c(1,.5),1,4L,TRUE,c(10,NA_real_))',
    'stopifnot(t$stat[2]==0,is.na(t$pvalue[2]),isTRUE(all.equal(t$pvalue[1],pt(1/sqrt(.5)-1,10,lower.tail=FALSE),tolerance=1e-15)))',
    'lrt <- call("rsdeseq2_lrt_pvalues",c(6,8),2)',
    'stopifnot(identical(lrt,pchisq(c(6,8),2,lower.tail=FALSE)))',
    'cutoff <- call("rsdeseq2_default_cooks_cutoff",8L,2L)',
    'stopifnot(isTRUE(all.equal(cutoff,qf(.99,2,6),tolerance=1e-13)),is.null(call("rsdeseq2_default_cooks_cutoff",4L,4L)))',
    'answer <- call("rsdeseq2_normalized_counts", ct, rep(2,4), NULL)',
    'stopifnot(identical(answer, ct / 2))',
    'p <- c(.001,.04,NA_real_,.5)',
    'adjusted <- call("rsdeseq2_bh_adjust",p)',
    'stopifnot(identical(adjusted,p.adjust(p,"BH")))',
    'filtered <- call("rsdeseq2_independent_filtering",as.double(1:4),p,NULL,.1,TRUE)',
    'stopifnot(identical(filtered$padj,adjusted),length(filtered$theta)==50L,length(filtered$lo.fit$y)==50L,filtered$selected==1L)',
    'unfiltered <- call("rsdeseq2_independent_filtering",as.double(1:4),p,NULL,.1,FALSE)',
    'stopifnot(identical(unfiltered$padj,adjusted),is.null(unfiltered$lo.fit),length(unfiltered$theta)==0L,all(is.na(unfiltered$filtered)))',
    'geoCounts <- matrix(c(10,40,90,30,40,50,20,200,100),3,byrow=TRUE)',
    'geoFactors <- call("rsdeseq2_estimate_size_factors",geoCounts,c(5,25,50),NULL,0L)',
    'expectedFactors <- c(1.2,4,2); expectedFactors <- expectedFactors / exp(mean(log(expectedFactors)))',
    'stopifnot(isTRUE(all.equal(geoFactors,expectedFactors,tolerance=1e-12)))',
    'set.seed(42); ct <- matrix(as.double(rnbinom(320, mu=50, size=5)),40,8)',
    'dm <- cbind(1, rep(c(0,1),each=4))',
    'fit <- call("rsdeseq2_fit",ct,dm,NULL,rep(1,8),NULL,NULL,2L,0L,0L,10,1L,0L)',
    'stopifnot(is.null(fit$replaceCounts),fit$nRefit==0L,identical(dim(fit$mu),dim(ct)))'
  ), script)
  direct <- Sys.getenv("RSDESEQ2_NATIVE_BOUNDARY_R_EXEC")
  runtime <- Sys.getenv("RSDESEQ2_SANITIZER_RUNTIME")
  libraries <- Sys.getenv("RSDESEQ2_SANITIZER_LIBRARY_PATH")
  executable <- if (nzchar(direct)) direct else file.path(R.home("bin"), "Rscript")
  arguments <- if (nzchar(direct)) c("--vanilla", "--slave", "-f") else "--vanilla"
  output <- system2(executable, c(arguments, shQuote(script)),
                    env = c(if (nzchar(runtime)) paste0("DYLD_INSERT_LIBRARIES=", shQuote(runtime)),
                            if (nzchar(libraries)) paste0("DYLD_FALLBACK_LIBRARY_PATH=", shQuote(libraries))),
                    stdout = TRUE, stderr = TRUE, timeout = 60)
  expect_null(attr(output, "status"), info = paste(output, collapse = "\n"))
})
